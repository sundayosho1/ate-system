import type { MarketObservation, UtcTimestamp } from "@ate/domain";
import type { Timeframe } from "./calendar.js";
import type { DataQualityFinding } from "@ate/data-quality";
export type Basis = "LAST_TRADE" | "BID" | "ASK" | "MIDPOINT";
export type EvidenceClass = "VERIFIED_POINT_IN_TIME" | "EVENT_TIME_RECONSTRUCTION";
export type QualityEvidence = Readonly<{
  reportId: string;
  reportFingerprint: string;
  findings: readonly Pick<DataQualityFinding, "findingId" | "category" | "severity">[];
  suppressed: number;
}>;
export type Input = Readonly<{
  observation: MarketObservation;
  identity: string;
  sessionId: string;
  channel: string;
  origin: "REALTIME" | "HISTORICAL" | "FIXTURE";
  sourceFingerprint: string;
  artifactId: string;
  availability: "VERIFIED" | "UNKNOWN";
  sourcePublishedAt?: UtcTimestamp;
  quality?: QualityEvidence;
  continuity: "CONTINUOUS" | "GAP" | "UNKNOWN";
  orderingSequence?: string;
  warnings: readonly string[];
}>;
export type Stream = Readonly<{
  sourceId: string;
  instrumentId: string;
  channel: string;
  basis: Basis;
  sourceFingerprint: string;
  priceCurrency: string;
  volumeType: "TRADE_VOLUME" | "TICK_VOLUME" | "QUOTE_COUNT" | "NOT_AVAILABLE";
  volumeUnit: string;
}>;
export type Window = Readonly<{
  start: UtcTimestamp;
  end: UtcTimestamp;
  calendarFingerprint: string;
  timeframeFingerprint: string;
  sessionId: string;
}>;
export type Contribution = Readonly<{
  key: string;
  identity: string;
  source?: MarketObservation["source"];
  provenance?: MarketObservation["provenance"];
  observationId?: string;
  revisionOf?: string;
  eventAt: UtcTimestamp;
  receivedAt: UtcTimestamp;
  processedAt: UtcTimestamp;
  availableAt: UtcTimestamp;
  sourcePublishedAt?: UtcTimestamp;
  availability: "VERIFIED" | "UNKNOWN";
  sequence?: string;
  open: string;
  high: string;
  low: string;
  close: string;
  volume?: string;
  volumeUnit: string;
  volumeType: Stream["volumeType"];
  sourceFingerprint: string;
  artifactId: string;
  quality: readonly string[];
  suppressed: number;
  final: boolean;
  complete: boolean;
  start: UtcTimestamp;
  end: UtcTimestamp;
  revisionId?: string;
  barId?: string;
  contentFingerprint: string;
}>;
export type Revision = Readonly<{
  barId: string;
  revisionId: string;
  generation: number;
  parentRevisionId?: string;
  reason: "INITIAL" | "UPDATE" | "FINALIZATION" | "CORRECTION";
  correctedFields: readonly string[];
  state: "FORMING" | "WINDOW_ELAPSED" | "FINALIZED" | "CORRECTED" | "INCOMPLETE" | "INVALIDATED";
  final: boolean;
  coverage: "COMPLETE_COVERAGE" | "INCOMPLETE" | "UNKNOWN";
  ordering: "VERIFIED" | "UNCERTAIN";
  streamId: string;
  stream: Stream;
  timeframe: string;
  timeframeDefinition: Timeframe;
  window: Window;
  configurationFingerprint: string;
  constructionFingerprint: string;
  eventAt: UtcTimestamp;
  receivedAt: UtcTimestamp;
  processedAt: UtcTimestamp;
  computedAt: UtcTimestamp;
  committedAt: UtcTimestamp;
  publishedAt: UtcTimestamp;
  availableAt: UtcTimestamp;
  finalityAt?: UtcTimestamp;
  availability: "VERIFIED" | "UNKNOWN";
  open: string;
  high: string;
  low: string;
  close: string;
  volume?: string;
  count: number;
  constituents: readonly Contribution[];
  quality: readonly string[];
  suppressedEvidence: number;
  contentFingerprint: string;
  lineageFingerprint: string;
  researchQualified: false;
  tradingAuthorized: false;
}>;
export type WindowState = {
  barId: string;
  streamId: string;
  timeframe: string;
  window: Window;
  contributions: Contribution[];
};
export type Watermark = {
  lastSequence?: string;
  sessionId: string;
  through: UtcTimestamp | null;
  observedAt: UtcTimestamp | null;
  status: "UNKNOWN" | "CONTINUOUS" | "FENCED";
  coverage: "COMPLETE_COVERAGE" | "INCOMPLETE" | "UNKNOWN";
  evidenceId: string | null;
};
export type Checkpoint = {
  schemaVersion: 1;
  configurationFingerprint: string;
  policyFingerprint: string;
  generation: number;
  streams: Record<string, Stream>;
  watermarks: Record<string, Watermark>;
  windows: WindowState[];
  revisions: Revision[];
  publishedOperationIds: string[];
  fingerprint: string;
};
export type SnapshotRequest = Readonly<{
  streamId: string;
  timeframes: readonly string[];
  asOf: UtcTimestamp;
  cutoff: UtcTimestamp;
  evidenceClass?: EvidenceClass;
  includeProvisional?: boolean;
  includeIncomplete?: boolean;
  maxAgeMs?: number;
  configurationFingerprint?: string;
  calendarFingerprint?: string;
  correctionPolicy?: "AS_KNOWN" | "INITIAL_ONLY";
  requireQualityEvidence?: boolean;
}>;
export type Snapshot = Readonly<{
  snapshotId: string;
  streamId: string;
  sourceFingerprint: string;
  calendarFingerprint: string;
  asOf: UtcTimestamp;
  cutoff: UtcTimestamp;
  evidenceClass: EvidenceClass;
  selected: Readonly<Record<string, Revision>>;
  missing: Readonly<Record<string, string>>;
  staleness: Readonly<Record<string, number>>;
  consistency: "CONSISTENT" | "INCOMPLETE";
  configurationFingerprint: string;
  policyFingerprint: string;
  contentFingerprint: string;
}>;
